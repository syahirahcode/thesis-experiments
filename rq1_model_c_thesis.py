"""# Classification / Dense Layer"""

class MultiHeadEfficientNetV2S(nn.Module):

  def __init__(self, freeze_backbone=False):  # Default False untuk Model B Fine-Tuning
    super(MultiHeadEfficientNetV2S, self).__init__()

    # Load backbone EfficientNetV2S
    weights = models.EfficientNet_V2_S_Weights.DEFAULT
    self.backbone = models.efficientnet_v2_s(weights=weights)

    # UNFREEZE BACKBONE UNTUK FINE-TUNING MODEL B
    if freeze_backbone:
      for param in self.backbone.parameters():
        param.requires_grad = False
    else:
      for param in self.backbone.parameters():
        param.requires_grad = True

    # Ambil jumlah fitur input dan ganti classifier bawaan dengan Identity
    in_features = self.backbone.classifier[1].in_features
    self.backbone.classifier = nn.Identity()

    # Dropout untuk regularisasi
    self.dropout = nn.Dropout(p=0.3)

    # 3 Multi-Head Output Classifiers
    self.head_skintone = nn.Linear(in_features, 5)  # 5 kelas
    self.head_undertone = nn.Linear(in_features, 2)  # 2 kelas
    self.head_saturation = nn.Linear(in_features, 3)  # 3 kelas

  def forward(self, x):
    features = self.backbone(x)
    features = self.dropout(features)

    return {
        "head_skintone": self.head_skintone(features),
        "head_undertone": self.head_undertone(features),
        "head_saturation": self.head_saturation(features),
    }


def evaluate_split(model, dataloader, split_name, device):
  y_true = {"st": [], "ut": [], "sat": []}
  y_pred = {"st": [], "ut": [], "sat": []}

  with torch.no_grad():
    for images, targets in dataloader:
      images = images.to(device)

      outputs = model(images)

      preds_st = torch.argmax(outputs["head_skintone"], dim=1).cpu().numpy()
      preds_ut = torch.argmax(outputs["head_undertone"], dim=1).cpu().numpy()
      preds_sat = torch.argmax(outputs["head_saturation"], dim=1).cpu().numpy()

      y_pred["st"].extend(preds_st)
      y_pred["ut"].extend(preds_ut)
      y_pred["sat"].extend(preds_sat)

      y_true["st"].extend(targets["head_skintone"].numpy())
      y_true["ut"].extend(targets["head_undertone"].numpy())
      y_true["sat"].extend(targets["head_saturation"].numpy())

  # Perhitungan Metrik Macro-Averaged per Head
  results = []
  heads = [
      ("Skin Tone", "st"),
      ("Undertone", "ut"),
      ("Skin Saturation", "sat"),
  ]

  for head_label, key in heads:
    acc = accuracy_score(y_true[key], y_pred[key])
    prec, rec, f1, _ = precision_recall_fscore_support(
        y_true[key], y_pred[key], average="macro", zero_division=0
    )

    results.append({
        "Dataset Split": split_name,
        "Target Head": head_label,
        "Accuracy (%)": round(acc * 100, 2),
        "Precision (m) (%)": round(prec * 100, 2),
        "Recall (m) (%)": round(rec * 100, 2),
        "F1-Score (m) (%)": round(f1 * 100, 2),
    })

  return pd.DataFrame(results), y_true, y_pred


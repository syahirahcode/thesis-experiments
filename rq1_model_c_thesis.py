def apply_geometric_augmentation(image):
    """
    Menerapkan augmentasi geometrik (Flip Horizontal & Rotasi Ringan)
    secara acak khusus untuk Training Set (700 Data).
    """
    # 1. Random Horizontal Flip (Probabilitas 50%)
    if np.random.rand() > 0.5:
        image = cv2.flip(image, 1)

    # 2. Random Rotation Ringan (-10 sampai +10 derajat)
    if np.random.rand() > 0.5:
        angle = np.random.uniform(-10, 10)
        h, w = image.shape[:2]
        M = cv2.getRotationMatrix2D((w // 2, h // 2), angle, 1.0)
        image = cv2.warpAffine(image, M, (w, h), borderMode=cv2.BORDER_REFLECT_101)

    return image

print("Fungsi Augmentasi Geometrik (Khusus Training Set) siap digunakan.")

"""## Generator"""

SKIN_TONE_MAP = {'Fair': 0, 'Medium': 1, 'Tanned': 2, 'Deep': 3, 'Dark': 4}
UNDERTONE_MAP = {'Cool': 0, 'Warm': 1}
SATURATION_MAP = {'Low': 0, 'Medium': 1, 'High': 2}

class CIELABDataGeneratorModelC(Dataset):
  """Custom Dataset PyTorch untuk Model C (CIELAB Color Space).

  Mengintegrasikan fungsi: convert_to_cielab, resize_and_scale,
  apply_geometric_augmentation, dan normalize_pixels.
  """

  def __init__(self, df, img_dir, target_size=(224, 224), augment=False):
    self.df = df.reset_index(drop=True)
    self.img_dir = img_dir
    self.target_size = target_size
    self.augment = augment

  def __len__(self):
    return len(self.df)

  def __getitem__(self, idx):
    row = self.df.iloc[idx]
    img_path = os.path.join(self.img_dir, str(row['File Name']))
    img = cv2.imread(img_path)

    if img is None:
      # Fallback jika gambar rusak/tidak ditemukan
      img = np.zeros(
          (self.target_size[0], self.target_size[1], 3), dtype=np.uint8
      )
    else:
      # Memanggil konversi CIELAB menggantikan RGB
      img = convert_to_cielab(img)
      img = resize_and_scale(img)

    # Augmentasi geometrik (Khusus set pelatihan)
    if self.augment:
      img = apply_geometric_augmentation(img)

    # Normalisasi piksel [0.0, 1.0]
    img = normalize_pixels(img)

    # Ubah format matriks dari NumPy (H, W, C) ke PyTorch Tensor (C, H, W)
    img_tensor = torch.tensor(img, dtype=torch.float32).permute(2, 0, 1)

    # Target label sebagai LongTensor (indeks integer untuk CrossEntropyLoss)
    y_skintone = torch.tensor(SKIN_TONE_MAP[row['Skin tone']], dtype=torch.long)
    y_undertone = torch.tensor(
        UNDERTONE_MAP[row['Under tone']], dtype=torch.long
    )
    y_saturation = torch.tensor(
        SATURATION_MAP[row['Skin saturation']], dtype=torch.long
    )

    y_dict = {
        'head_skintone': y_skintone,
        'head_undertone': y_undertone,
        'head_saturation': y_saturation,
    }

    return img_tensor, y_dict



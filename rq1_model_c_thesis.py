for epoch in range(EPOCHS):
  start_time = time.time()

  # --- TRAINING PHASE ---
  model_c.train()
  train_loss = 0.0
  train_correct_st, train_correct_ut, train_correct_sat = 0, 0, 0
  train_total = 0

  for images, targets in train_loader:
    images = images.to(device)
    y_skintone = targets["head_skintone"].to(device)
    y_undertone = targets["head_undertone"].to(device)
    y_saturation = targets["head_saturation"].to(device)

    optimizer.zero_grad()

    # Forward pass
    outputs = model_c(images)

    # Hitung loss gabungan dari 3 head
    loss_st = criterion(outputs["head_skintone"], y_skintone)
    loss_ut = criterion(outputs["head_undertone"], y_undertone)
    loss_sat = criterion(outputs["head_saturation"], y_saturation)

    loss = loss_st + loss_ut + loss_sat

    # Backward pass & Optimization
    loss.backward()
    optimizer.step()

    train_loss += loss.item()

    # Perhitungan jumlah prediksi benar (Training)
    preds_st = torch.argmax(outputs["head_skintone"], dim=1)
    preds_ut = torch.argmax(outputs["head_undertone"], dim=1)
    preds_sat = torch.argmax(outputs["head_saturation"], dim=1)

    train_correct_st += (preds_st == y_skintone).sum().item()
    train_correct_ut += (preds_ut == y_undertone).sum().item()
    train_correct_sat += (preds_sat == y_saturation).sum().item()
    train_total += images.size(0)

  avg_train_loss = train_loss / len(train_loader)

  # Hitung persentase akurasi Training per head & mean
  t_acc_st = (train_correct_st / train_total) * 100
  t_acc_ut = (train_correct_ut / train_total) * 100
  t_acc_sat = (train_correct_sat / train_total) * 100
  t_acc_mean = (t_acc_st + t_acc_ut + t_acc_sat) / 3

  # --- VALIDATION PHASE ---
  model_c.eval()
  val_loss = 0.0
  val_correct_st, val_correct_ut, val_correct_sat = 0, 0, 0
  val_total = 0

  with torch.no_grad():
    for images, targets in val_loader:
      images = images.to(device)
      y_skintone = targets["head_skintone"].to(device)
      y_undertone = targets["head_undertone"].to(device)
      y_saturation = targets["head_saturation"].to(device)

      outputs = model_c(images)

      loss_st = criterion(outputs["head_skintone"], y_skintone)
      loss_ut = criterion(outputs["head_undertone"], y_undertone)
      loss_sat = criterion(outputs["head_saturation"], y_saturation)

      loss = loss_st + loss_ut + loss_sat
      val_loss += loss.item()

      # Perhitungan jumlah prediksi benar (Validation)
      preds_st = torch.argmax(outputs["head_skintone"], dim=1)
      preds_ut = torch.argmax(outputs["head_undertone"], dim=1)
      preds_sat = torch.argmax(outputs["head_saturation"], dim=1)

      val_correct_st += (preds_st == y_skintone).sum().item()
      val_correct_ut += (preds_ut == y_undertone).sum().item()
      val_correct_sat += (preds_sat == y_saturation).sum().item()
      val_total += images.size(0)

  avg_val_loss = val_loss / len(val_loader)

  # Hitung persentase akurasi Validation per head & mean
  v_acc_st = (val_correct_st / val_total) * 100
  v_acc_ut = (val_correct_ut / val_total) * 100
  v_acc_sat = (val_correct_sat / val_total) * 100
  v_acc_mean = (v_acc_st + v_acc_ut + v_acc_sat) / 3

  elapsed_time = time.time() - start_time

  # Simpan ke Histori
  history["train_loss"].append(avg_train_loss)
  history["val_loss"].append(avg_val_loss)
  history["train_acc_st"].append(t_acc_st)
  history["train_acc_ut"].append(t_acc_ut)
  history["train_acc_sat"].append(t_acc_sat)
  history["train_acc_mean"].append(t_acc_mean)
  history["val_acc_st"].append(v_acc_st)
  history["val_acc_ut"].append(v_acc_ut)
  history["val_acc_sat"].append(v_acc_sat)
  history["val_acc_mean"].append(v_acc_mean)

  # Simpan bobot model terbaik berdasarkan Val Loss
  if avg_val_loss < best_val_loss:
    best_val_loss = avg_val_loss
    torch.save(model_c.state_dict(), "best_model_c_rgb.pth")

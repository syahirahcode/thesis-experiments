def extract_pure_skin_roi(image_bgr, landmarker_instance):
  h, w, _ = image_bgr.shape
  rgb_img = cv2.cvtColor(image_bgr, cv2.COLOR_BGR2RGB)
  mp_image = mp.Image(image_format=mp.ImageFormat.SRGB, data=rgb_img)

  detection_result = landmarker_instance.detect(mp_image)

  if not detection_result.face_landmarks:
    return image_bgr

  landmarks = detection_result.face_landmarks[0]
  pts_all = np.array(
      [[int(l.x * w), int(l.y * h)] for l in landmarks], np.int32
  )

  mask = np.zeros((h, w), dtype=np.uint8)
  hull = cv2.convexHull(pts_all)
  cv2.fillConvexPoly(mask, hull, 255)

  for idx_list in [LIPS_IDX, LEFT_EYE_IDX, RIGHT_EYE_IDX]:
    pts_feature = np.array(
        [[int(landmarks[i].x * w), int(landmarks[i].y * h)] for i in idx_list],
        np.int32,
    )
    cv2.fillConvexPoly(mask, cv2.convexHull(pts_feature), 0)

  cropped_bgr = cv2.bitwise_and(image_bgr, image_bgr, mask=mask)
  return cropped_bgr


